// Hook: returns t(text) for the current language.
// Starts in English so server and first client render match, then switches.
export function useT() {
  const [lang, setLang] = useState("en");
  useEffect(() => {
    const sync = () => setLang(getSavedLang());
    sync();
    window.addEventListener(LANG_EVENT, sync);
    return () => window.removeEventListener(LANG_EVENT, sync);
  }, []);
  return (text) => DICT[lang]?.[text] ?? text;
}

// Drop-in component for JSX text: <T>Sign out</T>
export function T({ children }) {
  const t = useT();
  return t(String(children));
}
